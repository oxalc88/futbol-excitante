import { chromium } from "playwright";
import fs from "node:fs";
import path from "node:path";
const objectiveId = process.env.WIP_SECTION ?? "ai-match";
const baseUrl = process.env.WIP_BASE_URL ?? "http://127.0.0.1:5173/src/apps/browser/index.html?mode=ai-match";
const durationMs = Number(process.env.WIP_VIDEO_MS ?? 15000);
const outDir = path.join("docs", "evidence", objectiveId);
const rawDir = path.join(outDir, "raw");
fs.mkdirSync(rawDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: rawDir, size: { width: 1280, height: 720 } } });
const page = await context.newPage();
await page.goto(baseUrl, { waitUntil: "networkidle" });
await page.waitForTimeout(durationMs);
const video = page.video();
await context.close();
const rawPath = video ? await video.path() : null;
await browser.close();
if (!rawPath) throw new Error("video capture failed");
const webm = path.join(outDir, "ai-match.webm");
fs.copyFileSync(rawPath, webm);
fs.writeFileSync(path.join(outDir, "video-reference.json"), JSON.stringify({ schemaVersion: 1, objectiveId, commitSha: process.env.GITHUB_SHA ?? "local", workflowRunId: process.env.GITHUB_RUN_ID ?? null, artifactName: process.env.WIP_ARTIFACT_NAME ?? `video-${objectiveId}`, source: "playwright-recordVideo", videoFile: "ai-match.webm" }, null, 2) + "\n");
console.log(webm);
